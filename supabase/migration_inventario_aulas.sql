-- Inventario físico de aulas y asignaciones académicas.
-- Migración aditiva: conserva intactas las columnas y filas históricas de capacidad_academica.

create table if not exists public.aulas (
  id bigint generated by default as identity primary key,
  nucleo_id bigint not null references public.nucleos(id) on delete cascade,
  extension_id bigint null references public.extensiones(id) on delete set null,
  nombre text not null,
  capacidad_puestos integer not null check (capacidad_puestos > 0),
  observaciones text,
  activa boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint aulas_nombre_no_vacio check (length(trim(nombre)) > 0)
);

create unique index if not exists aulas_unicas_sede_nombre
  on public.aulas (nucleo_id, coalesce(extension_id, 0), lower(trim(nombre)));

create table if not exists public.asignaciones_aulas (
  id bigint generated by default as identity primary key,
  nucleo_id bigint not null references public.nucleos(id) on delete cascade,
  aula_id bigint not null references public.aulas(id) on delete cascade,
  capacidad_academica_id bigint not null references public.capacidad_academica(id) on delete cascade,
  turno text not null check (turno in ('Mañana','Tarde','Noche')),
  hora_inicio time,
  hora_fin time,
  dias text,
  seccion text,
  estudiantes_asignados integer not null default 0 check (estudiantes_asignados >= 0),
  observaciones text,
  creado_en timestamptz not null default now(),
  constraint asignacion_horas_validas check (
    (hora_inicio is null and hora_fin is null) or
    (hora_inicio is not null and hora_fin is not null and hora_fin > hora_inicio)
  )
);

create index if not exists aulas_nucleo_idx on public.aulas(nucleo_id);
create index if not exists asignaciones_aula_idx on public.asignaciones_aulas(aula_id);
create index if not exists asignaciones_capacidad_idx on public.asignaciones_aulas(capacidad_academica_id);

alter table public.aulas enable row level security;
alter table public.asignaciones_aulas enable row level security;

drop policy if exists "responsables ven aulas de su nucleo" on public.aulas;
create policy "responsables ven aulas de su nucleo" on public.aulas
for select to authenticated
using (public.es_admin_unes() or nucleo_id::text = public.mi_nucleo_unes());

drop policy if exists "responsables agregan aulas de su nucleo" on public.aulas;
create policy "responsables agregan aulas de su nucleo" on public.aulas
for insert to authenticated
with check (public.es_admin_unes() or nucleo_id::text = public.mi_nucleo_unes());

drop policy if exists "admin gestiona aulas" on public.aulas;
create policy "admin gestiona aulas" on public.aulas
for all to authenticated
using (public.es_admin_unes())
with check (public.es_admin_unes());

drop policy if exists "responsables ven asignaciones de su nucleo" on public.asignaciones_aulas;
create policy "responsables ven asignaciones de su nucleo" on public.asignaciones_aulas
for select to authenticated
using (public.es_admin_unes() or nucleo_id::text = public.mi_nucleo_unes());

drop policy if exists "responsables crean asignaciones de su nucleo" on public.asignaciones_aulas;
create policy "responsables crean asignaciones de su nucleo" on public.asignaciones_aulas
for insert to authenticated
with check (
  public.es_admin_unes() or
  (nucleo_id::text = public.mi_nucleo_unes()
   and exists (select 1 from public.aulas a where a.id = aula_id and a.nucleo_id = asignaciones_aulas.nucleo_id)
   and exists (select 1 from public.capacidad_academica c where c.id = capacidad_academica_id and c.nucleo_id = asignaciones_aulas.nucleo_id))
);

drop policy if exists "admin gestiona asignaciones" on public.asignaciones_aulas;
create policy "admin gestiona asignaciones" on public.asignaciones_aulas
for all to authenticated
using (public.es_admin_unes())
with check (public.es_admin_unes());

grant select, insert on public.aulas to authenticated;
grant select, insert on public.asignaciones_aulas to authenticated;
grant usage, select on all sequences in schema public to authenticated;
