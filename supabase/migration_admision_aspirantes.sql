-- Registro individual de aspirantes para el proceso de admisión.
-- Los datos de identificación y los estados de evaluación quedan protegidos por RLS.
-- No se almacenan diagnósticos, informes clínicos ni notas psicológicas.

create table if not exists public.aspirantes_admision (
  id bigint generated by default as identity primary key,
  nucleo_id bigint not null references public.nucleos(id) on delete restrict,
  extension_id bigint null references public.extensiones(id) on delete set null,
  nucleo_origen_pdf text,
  apellidos text not null,
  nombres text not null,
  cedula text not null,
  genero text,
  pnf text not null,
  proceso text not null default 'ENERO I-2027',
  semana text,
  prueba_medica_estado text not null default 'Pendiente'
    check (prueba_medica_estado in ('Pendiente','Aprobado','No aprobado')),
  prueba_medica_fecha date,
  prueba_psicologica_estado text not null default 'Pendiente'
    check (prueba_psicologica_estado in ('Pendiente','Aprobado','No aprobado')),
  prueba_psicologica_fecha date,
  prueba_fisica_estado text not null default 'Pendiente'
    check (prueba_fisica_estado in ('Pendiente','Aprobado','No aprobado')),
  prueba_fisica_fecha date,
  estado_general text generated always as (
    case
      when prueba_medica_estado = 'No aprobado'
        or prueba_psicologica_estado = 'No aprobado'
        or prueba_fisica_estado = 'No aprobado' then 'No aprobado'
      when prueba_medica_estado = 'Aprobado'
        and prueba_psicologica_estado = 'Aprobado'
        and prueba_fisica_estado = 'Aprobado' then 'Aprobado para ingresar'
      else 'En evaluación'
    end
  ) stored,
  creado_en timestamptz not null default now(),
  constraint aspirantes_nombres_no_vacios check (
    length(trim(apellidos)) > 0 and length(trim(nombres)) > 0
  ),
  constraint aspirantes_cedula_no_vacia check (length(trim(cedula)) > 0)
);

create index if not exists aspirantes_nucleo_idx
  on public.aspirantes_admision(nucleo_id);
create index if not exists aspirantes_pnf_idx
  on public.aspirantes_admision(pnf);
create index if not exists aspirantes_cedula_idx
  on public.aspirantes_admision(cedula);
create index if not exists aspirantes_proceso_idx
  on public.aspirantes_admision(proceso);

alter table public.aspirantes_admision enable row level security;

drop policy if exists "usuarios consultan aspirantes de su nucleo" on public.aspirantes_admision;
create policy "usuarios consultan aspirantes de su nucleo"
  on public.aspirantes_admision for select to authenticated
  using (public.es_admin_unes() or nucleo_id::text = public.mi_nucleo_unes());

drop policy if exists "usuarios registran aspirantes de su nucleo" on public.aspirantes_admision;
create policy "usuarios registran aspirantes de su nucleo"
  on public.aspirantes_admision for insert to authenticated
  with check (
    public.es_admin_unes() or
    (nucleo_id::text = public.mi_nucleo_unes()
      and (extension_id is null or exists (
        select 1 from public.extensiones e
        where e.id = extension_id and e.nucleo_id = aspirantes_admision.nucleo_id
      )))
  );

drop policy if exists "usuarios actualizan aspirantes de su nucleo" on public.aspirantes_admision;
create policy "usuarios actualizan aspirantes de su nucleo"
  on public.aspirantes_admision for update to authenticated
  using (public.es_admin_unes() or nucleo_id::text = public.mi_nucleo_unes())
  with check (
    public.es_admin_unes() or
    (nucleo_id::text = public.mi_nucleo_unes()
      and (extension_id is null or exists (
        select 1 from public.extensiones e
        where e.id = extension_id and e.nucleo_id = aspirantes_admision.nucleo_id
      )))
  );

drop policy if exists "admin elimina aspirantes" on public.aspirantes_admision;
create policy "admin elimina aspirantes"
  on public.aspirantes_admision for delete to authenticated
  using (public.es_admin_unes());

grant select, insert, update, delete on public.aspirantes_admision to authenticated;
grant usage, select on sequence public.aspirantes_admision_id_seq to authenticated;
